/* ==========================================
   ABRIR / FECHAR DOSSIÊ
========================================== */

function toggleBlock(button) {

    const bloco =
        button.nextElementSibling;


    bloco.classList.toggle("active");


    const simbolo =
        button.querySelectorAll("span")[1];


    if (
        bloco.classList.contains("active")
    ) {

        simbolo.innerText = "−";

    } else {

        simbolo.innerText = "+";

    }

}


